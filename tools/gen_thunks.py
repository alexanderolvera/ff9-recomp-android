"""Generic engine-call thunks (no game data): N numbered thunks that tail-jump through
ue_icall_table[i], and N numbered "missing" stubs. The host assigns them to UnityEngine's
internal calls at run time.  py gen_thunks.py <outdir> [N]"""
import os, sys
out = sys.argv[1]
n = int(sys.argv[2]) if len(sys.argv) > 2 else 6144
os.makedirs(out, exist_ok=True)
with open(os.path.join(out, "ue_thunks.S"), "w") as f:
    f.write("// generated by tools/gen_thunks.py\n    .text\n    .p2align 2\n")
    for i in range(n):
        f.write(f"    .globl ue_thunk_{i}\n    .hidden ue_thunk_{i}\nue_thunk_{i}:\n")
        f.write(f"    adrp x16, ue_icall_table+{i * 8}\n    ldr x16, [x16, :lo12:ue_icall_table+{i * 8}]\n    br x16\n")
with open(os.path.join(out, "ue_stubs.c"), "w") as f:
    f.write("/* generated by tools/gen_thunks.py */\nvoid ue_icall_hit(int index);\n")
    for i in range(n):
        f.write(f"static long s{i}(void) {{ ue_icall_hit({i}); return 0; }}\n")
    # hidden: the thunks address it directly, which a shared library only allows for local symbols
    f.write(f"const int ue_thunk_count = {n};\n__attribute__((visibility(\"hidden\"))) const void *ue_icall_table[{n}] = {{\n")
    for i in range(n):
        f.write(f"  (const void *)s{i},\n")
    f.write("};\n")
    for i in range(n):
        f.write(f"void ue_thunk_{i}(void);\n")
    f.write(f"const void *const ue_thunks[{n}] = {{\n")
    for i in range(n):
        f.write(f"  (const void *)ue_thunk_{i},\n")
    f.write("};\n")
print(n, "thunks")
