"""Tables for the Mono test host, from the user's own managed DLLs.

  py gen_host_tables.py <Managed dir> <outdir>

  <outdir>/ue_icalls.c     one named stub per UnityEngine internal call + its registration
  <outdir>/tokens/<asm>.txt  MethodDef tokens with IL bodies, outside generic types/methods
                             (what the host JIT-compiles)
Derived from the game's DLLs: keep out of any repository.
"""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cil import Assembly

managed, out = sys.argv[1], sys.argv[2]
os.makedirs(os.path.join(out, "tokens"), exist_ok=True)


def type_names(a):
    tds = a.table("TypeDef")
    enclosing = {r["Nested"]: r["Enclosing"] for r in a.table("NestedClass")}

    def full(ti):
        r = tds[ti - 1]
        if ti in enclosing:
            return full(enclosing[ti]) + "/" + r["Name"]
        return (r["Namespace"] + "." if r["Namespace"] else "") + r["Name"]
    owner = {}
    md_n = len(a.table("MethodDef"))
    for ti, r in enumerate(tds, 1):
        end = tds[ti]["MethodList"] if ti < len(tds) else md_n + 1
        for mi in range(r["MethodList"], end):
            owner[mi] = ti
    return full, owner


# ---- UnityEngine internal calls ----
ue = Assembly(os.path.join(managed, "UnityEngine.dll"))
full, owner = type_names(ue)
names = []
seen = set()
for mi, r in enumerate(ue.table("MethodDef"), 1):
    if r["ImplFlags"] & 0x1000:
        n = f"{full(owner[mi])}::{r['Name']}"
        if n not in seen:
            seen.add(n)
            names.append(n)
with open(os.path.join(out, "ue_icalls.c"), "w") as f:
    f.write("/* generated by gen_host_tables.py: one stub per UnityEngine internal call */\n")
    f.write("void ue_icall_hit(int index);\n")
    for i, n in enumerate(names):
        f.write(f"static long s{i}(void) {{ ue_icall_hit({i}); return 0; }}\n")
    f.write(f"const int ue_icall_count = {len(names)};\n")
    f.write("const char *const ue_icall_names[] = {\n")
    for n in names:
        f.write(f'  "{n}",\n')
    # Each internal call is registered with Mono as a jump thunk (ue_thunks.S) branching through
    # ue_icall_table[i] at call time; the table starts with the "missing" stubs and FF9Engine
    # fills it. (Registering managed code with Mono directly is order-sensitive: Mono resolves an
    # icall when it compiles a caller, which can happen while the engine is still registering.)
    f.write("};\nconst void *ue_icall_table[] = {\n")
    for i in range(len(names)):
        f.write(f"  (const void *)s{i},\n")
    f.write("};\n")
    for i in range(len(names)):
        f.write(f"void ue_thunk_{i}(void);\n")
    f.write("const void *const ue_icall_fns[] = {\n")
    for i in range(len(names)):
        f.write(f"  (const void *)ue_thunk_{i},\n")
    f.write("};\n")
with open(os.path.join(out, "ue_thunks.S"), "w") as f:
    f.write("// generated by gen_host_tables.py: tail-jump through ue_icall_table, argument registers untouched\n")
    f.write("    .text\n    .p2align 2\n")
    for i in range(len(names)):
        f.write(f"    .globl ue_thunk_{i}\n    .hidden ue_thunk_{i}\nue_thunk_{i}:\n")
        f.write("    adrp x16, ue_icall_table\n    add x16, x16, :lo12:ue_icall_table\n")
        f.write(f"    ldr x16, [x16, #{i * 8}]\n    br x16\n")
print(len(names), "UnityEngine internal calls")

# ---- tokens to JIT ----
SKIP = {"mscorlib", "System", "System.Core", "System.Runtime.Serialization"}
for fn in sorted(os.listdir(managed)):
    if not fn.endswith(".dll") or fn[:-4] in SKIP:
        continue
    a = Assembly(os.path.join(managed, fn))
    full, owner = type_names(a)
    gtypes, gmethods = set(), set()
    for r in a.table("GenericParam"):
        kind, idx = r["Owner"]
        (gtypes if kind == "TypeDef" else gmethods).add(idx)
    enclosing = {r["Nested"]: r["Enclosing"] for r in a.table("NestedClass")}

    def generic_type(ti):
        while ti:
            if ti in gtypes:
                return True
            ti = enclosing.get(ti)
        return False
    toks = []
    for mi, r in enumerate(a.table("MethodDef"), 1):
        if not r["RVA"] or mi in gmethods or generic_type(owner[mi]):
            continue
        toks.append(0x06000000 | mi)
    with open(os.path.join(out, "tokens", fn[:-4] + ".txt"), "w") as f:
        f.write("\n".join(f"{t:08x}" for t in toks) + "\n")
    print(f"{fn}: {len(toks)} methods to JIT")
